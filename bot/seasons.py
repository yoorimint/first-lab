"""계절 공개 순서 (11/5 운영자 승인): 검색이 몰리는 시기에 맞춰 초안 공개 순서를 바꾼다.

예약 공개 시각은 그대로 두고(하루 공개량 유지), 시각이 되면
  1) 시즌 중인 글(검색이 몰리기 몇 주 전 ~ 마감)  2) 계절과 상관없는 글  3) 시즌이 막 지난 글
순서로 고른다 (같은 순위 안에서는 오래된 초안부터). 시즌이 지난 글은 다음 시즌까지 미뤄지되,
다른 글이 없으면 공개된다.

시즌표: (키워드에 들어가는 낱말들, [(시작 월-일, 끝 월-일), …]) — 시작은 검색이 오르기 몇 주 전,
끝은 신고·신청 마감 무렵. 연도를 넘는 구간(예: 12-01 ~ 01-25)도 된다. 표만 고치면 반영된다.
"""
from __future__ import annotations

import datetime as dt

SEASONS: tuple[tuple[tuple[str, ...], tuple[tuple[str, str], ...]], ...] = (
    (("중간예납",), (("10-20", "11-30"),)),                          # 11월 납부 — 종합소득세보다 먼저 봐야 함 (11/11 #1019 가 5월 시즌으로 잡힘)
    (("종합소득세", "종소세"), (("03-20", "06-30"),)),              # 5월 신고 (성실신고 6월)
    (("연말정산",), (("11-20", "02-28"),)),                          # 1~2월
    (("부가세", "부가가치세"), (("12-01", "01-25"), ("06-01", "07-25"))),  # 1월·7월 확정신고
    (("종부세", "종합부동산세"), (("10-15", "12-15"),)),             # 12월 납부
    (("재산세",), (("06-01", "07-31"), ("08-15", "09-30"))),          # 7월·9월
    (("자동차세",), (("12-01", "01-31"), ("05-20", "06-30"))),        # 연납 1월, 6월·12월
    (("근로장려금", "자녀장려금"), (("04-01", "05-31"),)),           # 5월 정기신청
    (("에너지바우처",), (("06-01", "12-31"),)),                      # 6~12월 신청
    (("독감", "인플루엔자"), (("08-20", "11-30"),)),                 # 가을 접종
    (("윈터타이어", "스노우타이어", "스노타이어"), (("10-01", "12-31"),)),
    (("캠핑",), (("03-01", "10-15"),)),
)

IN, NONE, OFF = 0, 1, 2  # 공개 우선순위 (작을수록 먼저)


def _md(text: str) -> tuple[int, int]:
    m, d = text.split("-")
    return int(m), int(d)


def in_window(today: dt.date, start: str, end: str) -> bool:
    s, e, t = _md(start), _md(end), (today.month, today.day)
    return s <= t <= e if s <= e else (t >= s or t <= e)  # 연도를 넘는 구간


def rank(text: str, today: dt.date) -> int:
    """글(키워드+제목)의 공개 우선순위: 시즌 중 IN, 계절 무관 NONE, 시즌 지남 OFF."""
    compact = text.replace(" ", "")
    for words, windows in SEASONS:
        if any(w in compact for w in words):
            return IN if any(in_window(today, s, e) for s, e in windows) else OFF
    return NONE
